// The coding profile: the one set of Codex tools, sandbox rules and approval
// rules every agent gets when the operator turns coding on
// (RUNTIME_CODING_ENABLED=1). It lives in code, not configuration, so a rule
// only changes through review and the pin tests (test/codex/coding.test.ts).
//
// Verified against the pin (coding probes, 2026-10-21):
// - A granular approval policy with `sandbox_approval: false` (config.ts)
//   runs commands and file changes inside the sandbox without asking, asks
//   before a command a `prompt` rule below matches, and refuses without
//   asking what would leave the sandbox (an escalation request, a patch
//   outside the workspace, which an approval would write unsandboxed) and
//   what Codex flags as dangerous (`rm -f`, `sudo`). A command the sandbox
//   refuses is reported to the model, never retried unsandboxed.
// - The permissions profile denies the adapter's state directory and /tmp,
//   which keeps every command, asked or not, inside the sandbox: reads
//   limited to the system, the toolchains and this chat's workspace; writes
//   limited to the workspace and the chat's scratch directory; no network.
// - Files are not approved one by one: the platform keeps every version, so
//   a deleted or overwritten file can be restored. The prompt rules are best
//   effort (a command inside `python -c` or a script is not parsed); the
//   versions are the real protection.

export const PERMISSION_PROFILE = "truex";

// Commands that publish work or destroy history git cannot restore. Each
// always asks, whatever the member allowed for this chat for other commands.
// Codex validates `match` / `not_match` when it loads the file, so a rule
// that stops matching what it should fails at startup.
export const RULES = `# Generated by the Truex runtime adapter. Do not edit.
prefix_rule(
    pattern = ["git", "push"],
    decision = "prompt",
    justification = "Pushing publishes code; it always needs the user's approval.",
    match = [["git", "push"], "git push origin main"],
    not_match = ["git status"],
)
prefix_rule(
    pattern = ["git", "reset", "--hard"],
    decision = "prompt",
    justification = "A hard reset discards uncommitted work.",
    match = ["git reset --hard", "git reset --hard HEAD~1"],
    not_match = ["git reset HEAD a.txt"],
)
prefix_rule(
    pattern = ["git", "clean"],
    decision = "prompt",
    justification = "git clean deletes untracked files.",
    match = ["git clean -fd"],
    not_match = ["git status"],
)
`;

// Tells the model what it can do, in the words it should use with the user.
// Which document tools exist. Without it models reach for pandoc, LibreOffice,
// weasyprint or `pip install`, none of which the sandbox has, and retry other
// missing tools until they give up (one chat: 36 commands, 19 failed, 749k
// tokens, no PDF, while reportlab was installed). The libraries are the pinned
// toolchain's (toolchain/requirements.in); keep the two in step.
export const DOCUMENT_INSTRUCTIONS = `For Word, Excel, PowerPoint and PDF files use Python with the installed libraries: python-docx (.docx), openpyxl (.xlsx), python-pptx (.pptx), reportlab to write PDF and pypdf to read it. Nothing else can be installed (no pip, brew or apt), and pandoc, LibreOffice, wkhtmltopdf, weasyprint and the markdown package are not available. If an approach fails twice, do not try other tools for it; say plainly what you could not make.`;

// Kept short and stable: it is part of every request's cached prefix.
// /tmp is denied (see `codingConfig`); models reach for it by habit, so the
// scratch directory is named.
export const CODING_INSTRUCTIONS = `You can create, edit and delete files in this chat and run code: Node.js and Python are available, with no internet access. Use this when the user asks for a file, for code, or to run, test or check something; otherwise just answer. Files you create appear in the chat for the user to open. For temporary files use $TMPDIR, never /tmp. When you talk to the user, refer to files by their name only. Never mention workspaces, directories, paths, commands, terminals, sandboxes, tool names or approvals. If an action is declined, do not retry it; tell the user what you could not do. These file and code tools are yours in this chat even if earlier instructions say you have no files or code execution: when the user asks for a file, make it. ${DOCUMENT_INSTRUCTIONS}`;

// Added for a chat with skills. The skills catalog shows each skill by its
// stored path, which the shell cannot list; $SKILLS names every skill of the
// chat by its own name (see `linkSkills`), and keeps the state path out of
// the command rows the user sees.
export const SKILL_SCRIPT_INSTRUCTIONS = `A skill's files are also at $SKILLS/<skill name>/. Run a skill's scripts from there, for example python3 "$SKILLS/<skill name>/scripts/<script>".`;

// With a network policy (network.ts), in place of "no internet access". A
// blocked request becomes a card the user answers; another route around it
// would only be blocked again.
export const NETWORK_INSTRUCTIONS = `Internet access is limited to the sites this chat may use. If a request is blocked, do not try another way to reach that site; tell the user which site was blocked, that they can allow it, and that you will continue when they ask you to try again.`;

export function codingInstructions(
  hasSkills: boolean,
  hasNetwork = false,
): string {
  const base = hasNetwork
    ? `${CODING_INSTRUCTIONS.replace(", with no internet access", "")} ${NETWORK_INSTRUCTIONS}`
    : CODING_INSTRUCTIONS;
  return hasSkills ? `${base} ${SKILL_SCRIPT_INSTRUCTIONS}` : base;
}

export interface CodingPaths {
  // The adapter's state directory: every chat, home and record lives here.
  readonly stateDir: string;
  // This chat's workspace ($WORKSPACE for commands).
  readonly workspace: string;
  // This chat's scratch directory (HOME and TMPDIR for commands).
  readonly scratch: string;
  // A readable package.json at the top of the state directory, when one is
  // needed (see `packageBoundary`).
  readonly packageBoundary?: string | undefined;
  // The chat's skill directories, readable so the model can run a skill's
  // scripts. Never writable: a skill is shared by every chat that uses it.
  readonly skills?: readonly string[];
  // The chat's directory of links to those skills, one per skill name
  // ($SKILLS). Set when the chat has skills.
  readonly skillLinks?: string | undefined;
  // The run's sandbox network (network.ts). Absent: no network.
  readonly network?: NetworkSettings | undefined;
}

// What the adapter works out once at startup when coding is on.
export interface CodingSetup {
  readonly toolchains: Toolchains;
  readonly packageBoundary?: string | undefined;
  // Tests only, never read from the environment: the network proxy forwards
  // to a loopback stand-in for the internet (test/support/network-fixture.ts)
  // through this upstream proxy environment.
  readonly networkTestEnv?: Readonly<Record<string, string>> | undefined;
}

// Node looks for the nearest package.json in every directory above a script
// and stops with ERR_INVALID_PACKAGE_CONFIG when one exists that the sandbox
// will not let it read. Inside the denied state directory nothing exists
// there, but a state directory inside a project (a local checkout) has the
// project's package.json above it, and every `node file.js` would fail. A
// readable, empty one at the top of the state directory ends the search
// first, as if the state directory stood alone. Undefined when no directory
// above it has a package.json, which is the case on a deployed runtime.
export const PACKAGE_BOUNDARY = `{ "//": "Written by the Truex runtime adapter. Do not edit." }\n`;

export function packageBoundary(stateDir: string): string | undefined {
  for (let dir = dirname(stateDir); ; dir = dirname(dir)) {
    if (existsSync(join(dir, "package.json")))
      return join(stateDir, "package.json");
    if (dirname(dir) === dir) return undefined;
  }
}

export interface Toolchains {
  // Extra read-only directories commands need (toolchain prefixes).
  readonly readRoots: readonly string[];
  // PATH for commands.
  readonly path: string;
}

// The toolchains commands may read and run, found once at startup: the Node
// prefix this adapter runs on, any operator-listed prefixes
// (RUNTIME_TOOLCHAIN_DIRS) and, on macOS, the system pieces Node, Python and
// git load outside the sandbox's minimal set. Only existing directories are
// listed.
export function detectToolchains(
  extra: readonly string[],
  platform = process.platform,
  nodePath = process.execPath,
): Toolchains {
  const nodePrefix = dirname(dirname(nodePath));
  const macos =
    platform === "darwin"
      ? [
          "/System/Library/OpenSSL",
          "/Library/Developer/CommandLineTools",
          "/opt/homebrew",
        ]
      : [];
  const readRoots = [
    ...new Set(
      [nodePrefix, ...extra, ...macos].filter((dir) => existsSync(dir)),
    ),
  ];
  // Operator-listed toolchains first: Node's own bin directory can hold
  // another python3 (Homebrew's /opt/homebrew/bin), which must not shadow the
  // toolchain that has the pinned libraries.
  const bins = [
    ...extra.map((dir) => join(dir, "bin")),
    dirname(nodePath),
    // The Command Line Tools binaries themselves: /usr/bin/git is an xcrun
    // shim that writes a cache under /var/folders, which the sandbox refuses.
    ...(platform === "darwin"
      ? ["/Library/Developer/CommandLineTools/usr/bin", "/opt/homebrew/bin"]
      : []),
  ].filter((dir) => existsSync(dir));
  const path = [
    ...new Set([
      ...bins,
      "/usr/local/bin",
      "/usr/bin",
      "/bin",
      "/usr/sbin",
      "/sbin",
    ]),
  ].join(":");
  return { readRoots, path };
}

// Config keys for a coding run. The filesystem entries are ordered from broad
// to narrow; Codex resolves the most specific path, so the workspace and
// scratch stay writable inside the denied state directory.
export function codingConfig(
  paths: CodingPaths,
  toolchains: Toolchains,
): Record<string, unknown> {
  const filesystem: Record<string, unknown> = { ":minimal": "read" };
  for (const dir of toolchains.readRoots) filesystem[dir] = "read";
  filesystem[paths.stateDir] = "deny";
  if (paths.packageBoundary) filesystem[paths.packageBoundary] = "read";
  for (const dir of paths.skills ?? []) filesystem[dir] = "read";
  if (paths.skillLinks) filesystem[paths.skillLinks] = "read";
  // Other chats' and processes' temporary files.
  filesystem["/tmp"] = "deny";
  filesystem["/private/tmp"] = "deny";
  filesystem[paths.scratch] = "write";
  filesystem[":workspace_roots"] = { ".": "write" };
  return {
    "features.shell_tool": true,
    "features.unified_exec": true,
    // item/fileChange/patchUpdated while the model writes a patch, so a long
    // file shows progress instead of nothing until the call is complete.
    // "Under development" upstream; pinned on explicitly so a change fails
    // the pin tests (test/codex/coding.test.ts).
    "features.apply_patch_streaming_events": true,
    ...paths.network?.features,
    [`permissions.${PERMISSION_PROFILE}`]: {
      filesystem,
      network: paths.network?.profile ?? { enabled: false },
    },
    shell_environment_policy: {
      inherit: "none",
      set: {
        PATH: toolchains.path,
        HOME: paths.scratch,
        TMPDIR: paths.scratch,
        // zsh ignores TMPDIR for heredocs and would use the denied /tmp/zsh.
        // A prefix, not a directory: files are named <scratch>/zsh<random>.
        TMPPREFIX: join(paths.scratch, "zsh"),
        LANG: "en_US.UTF-8",
        // Shown commands and output name the workspace by this variable.
        WORKSPACE: paths.workspace,
        ...(paths.skillLinks ? { SKILLS: paths.skillLinks } : {}),
        ...paths.network?.env,
      },
    },
  };
}

// A Codex model catalog with one entry, the run's model. Without it Codex
// falls back to metadata that offers no apply_patch tool and clamps the
// context window to 272k × 95% (`model_info_from_slug`). Codex reads the
// catalog once per process, so a change restarts the chat's process (see
// `catalogFingerprint`). `base_instructions` is required by the loader but
// never used: every thread starts with the agent's own prompt.
export function modelCatalog(
  model: ModelSettings,
  toolOutputTokenLimit: number,
): string {
  return JSON.stringify({
    models: [
      {
        slug: model.modelName,
        display_name: model.modelName,
        description: null,
        supported_reasoning_levels: [],
        shell_type: "shell_command",
        visibility: "none",
        supported_in_api: true,
        priority: 1,
        availability_nux: null,
        upgrade: null,
        support_verbosity: false,
        default_verbosity: null,
        // The pin has only the freeform form; the gateway offers it to
        // non-Responses providers as a function (model-gateway custom tools).
        apply_patch_tool_type: "freeform",
        truncation_policy: { mode: "tokens", limit: toolOutputTokenLimit },
        context_window: model.contextWindow,
        max_context_window: model.contextWindow,
        effective_context_window_percent: 95,
        experimental_supported_tools: [],
        base_instructions: "You are a helpful assistant.",
      },
    ],
  });
}

export function catalogFingerprint(catalog: string): string {
  return createHash("sha256").update(catalog).digest("hex");
}
